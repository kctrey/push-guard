#!/bin/sh
# Removes push-guard from git. Your local lists stay in ~/.config/git/push-guard unless you pass --purge.
set -eu
case "$(uname -s)" in MINGW* | MSYS* | CYGWIN*) WIN=1 ;; *) WIN= ;; esac
if [ -n "$WIN" ]; then
  # Same as install.sh: compare and pass C:/... paths, as git.exe stores them.
  export MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*'
  winpath() { cygpath -m "$1"; }
else
  winpath() { printf '%s\n' "$1"; }
fi
DEST="$(winpath "$HOME/.config/git/push-guard")"
INCLUDE="$(winpath "$HOME/.config/git/push-guard.gitconfig")"
MARK="# push-guard launcher (generated by install.sh)"

if [ "$(git config --global --get core.hooksPath || true)" = "$DEST/hooks" ]; then
  git config --global --unset core.hooksPath
fi
# Names only (one per line), so folder names with spaces survive; then compare each value.
git config --global --name-only --get-regexp '^includeif\..*\.path$' 2>/dev/null | while IFS= read -r key; do
  # `if`, not `[ ] && …`: under set -e a false test as the loop's last command aborts the script.
  if [ "$(git config --global --get "$key" || true)" = "$INCLUDE" ]; then
    git config --global --unset "$key"
  fi
done
rm -f "$INCLUDE"
if [ -L "$HOME/.local/bin/push-guard" ]; then rm -f "$HOME/.local/bin/push-guard"; fi
# Windows launchers are plain files, not symlinks: only remove the ones install.sh wrote.
for f in "$HOME/.local/bin/push-guard" "$HOME/.local/bin/push-guard.cmd"; do
  if [ -f "$f" ] && grep -qF "${MARK#\# }" "$f"; then rm -f "$f"; fi
done

if [ "${1:-}" = "--purge" ]; then
  rm -rf "$DEST"
  echo "push-guard removed, including your local lists."
else
  echo "push-guard removed from git. Local lists kept in $DEST (delete with --purge)."
fi
