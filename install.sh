#!/bin/sh
# push-guard installer (macOS / Linux, or Windows from Git Bash). Safe to re-run: it updates the
# code and keeps your local lists (customer-terms.txt, allow.txt, reviewed.tsv, term-sources.txt).
#
#   ./install.sh                     guard every git repo on this machine (recommended)
#   ./install.sh ~/work ~/Projects   guard only repos inside these folders
set -eu

case "$(uname -s)" in MINGW* | MSYS* | CYGWIN*) WIN=1 ;; *) WIN= ;; esac
if [ -n "$WIN" ]; then
  # git.exe is a native Windows program: give it C:/... paths, never Git Bash's /c/... paths, and
  # stop Git Bash from rewriting arguments such as "includeIf.gitdir/i:C:/work/.path" on the way.
  export MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*'
  winpath() { cygpath -m "$1"; }
else
  winpath() { printf '%s\n' "$1"; }
fi

SRC="$(cd "$(dirname "$0")" && pwd -P)"
DEST="$(winpath "$HOME/.config/git/push-guard")"
INCLUDE="$(winpath "$HOME/.config/git/push-guard.gitconfig")"
HOOKS="applypatch-msg commit-msg post-applypatch post-checkout post-commit post-merge post-rewrite
pre-applypatch pre-auto-gc pre-commit pre-merge-commit pre-rebase prepare-commit-msg
push-to-checkout reference-transaction post-update pre-receive update proc-receive
sendemail-validate fsmonitor-watchman p4-changelist p4-prepare-changelist p4-post-changelist p4-pre-submit
post-index-change"
MARK="# push-guard launcher (generated by install.sh)"

if [ -n "$WIN" ]; then
  # "python3" is usually the Microsoft Store placeholder on Windows, so try each name and keep
  # the first that really runs Python 3.8+.
  PY=
  for c in "py -3" python python3; do
    if $c -c 'import sys; sys.exit(sys.version_info < (3, 8))' >/dev/null 2>&1; then PY="$c"; break; fi
  done
  [ -n "$PY" ] || {
    echo "push-guard needs Python 3.8+ — install it from https://www.python.org/downloads/windows/" >&2
    echo "(the Microsoft Store 'python3' placeholder doesn't count), then re-run this." >&2
    exit 1
  }
  PYEXE="$(cygpath -m "$($PY -c 'import sys; print(sys.executable)')")"
else
  command -v python3 >/dev/null || { echo "push-guard needs python3 — install it first." >&2; exit 1; }
fi

mkdir -p "$DEST/hooks"
cp "$SRC/push_guard.py" "$SRC/refresh_terms.py" "$DEST/"
cp "$SRC/hooks/_passthrough" "$DEST/hooks/"
chmod +x "$DEST/push_guard.py" "$DEST/refresh_terms.py" "$DEST/hooks/_passthrough"

if [ -n "$WIN" ]; then
  # Git Bash can't make real symlinks (ln -s silently copies), and a copied push_guard.py would
  # look for its lists in hooks/. Use small launchers that run the installed file instead.
  launcher() {
    printf '#!/bin/sh\n%s\npy="%s"\n[ -f "$py" ] || { echo "push-guard: Python not found at $py. Re-run install.sh." >&2; exit 1; }\nexec "$py" -I "%s" "$@"\n' \
      "$MARK" "$PYEXE" "$DEST/push_guard.py" > "$1"
    chmod +x "$1"
  }
  launcher "$DEST/hooks/pre-push"
  for h in $HOOKS; do cp "$DEST/hooks/_passthrough" "$DEST/hooks/$h"; done
  mkdir -p "$DEST/bin"
  launcher "$DEST/bin/push-guard"   # for Git Bash
  printf '@echo off\r\nrem %s\r\n"%s" -I "%s" %%*\r\nexit /b %%ERRORLEVEL%%\r\n' \
    "${MARK#\# }" "$(cygpath -w "$PYEXE")" "$(cygpath -w "$DEST/push_guard.py")" > "$DEST/bin/push-guard.cmd"  # for PowerShell / cmd
  # An earlier install on Windows left copies that kept their lists in hooks/: carry them over.
  if [ -f "$DEST/hooks/reviewed.tsv" ]; then
    grep -v '^#' "$DEST/hooks/reviewed.tsv" >> "$DEST/reviewed.tsv" || true
    rm -f "$DEST/hooks/reviewed.tsv"
  fi
  rm -rf "$DEST/hooks/pending"
else
  ln -sf ../push_guard.py "$DEST/hooks/pre-push"
  for h in $HOOKS; do ln -sf _passthrough "$DEST/hooks/$h"; done
fi
[ -f "$DEST/allow.txt" ] || cp "$SRC/allow.txt" "$DEST/allow.txt"
[ -f "$DEST/term-sources.txt" ] || cp "$SRC/term-sources.txt" "$DEST/term-sources.txt"

printf '# Enables push-guard (customer-data review before every push).\n[core]\n\thooksPath = %s\n' \
  "$DEST/hooks" > "$INCLUDE"

if [ $# -eq 0 ]; then
  current="$(git config --global --get core.hooksPath || true)"
  if [ -n "$current" ] && [ "$current" != "$DEST/hooks" ]; then
    echo "Your global core.hooksPath is already set to: $current" >&2
    echo "Not overwriting it. Re-run with folder arguments instead, e.g.  ./install.sh ~/work" >&2
    exit 1
  fi
  git config --global core.hooksPath "$DEST/hooks"
  scope="every git repo on this machine"
else
  scope=""
  for d in "$@"; do
    if [ -n "$WIN" ]; then
      dir="$(cd "$d" 2>/dev/null && pwd -W)" || { echo "Not a folder: $d" >&2; exit 1; }
    else
      dir="$(cd "$d" 2>/dev/null && pwd -P)" || { echo "Not a folder: $d" >&2; exit 1; }
    fi
    git config --global "includeIf.gitdir/i:$dir/.path" "$INCLUDE"
    scope="$scope $dir"
  done
fi

if [ -n "$WIN" ]; then
  if [ -d "$HOME/.local/bin" ]; then
    cp "$DEST/bin/push-guard" "$DEST/bin/push-guard.cmd" "$HOME/.local/bin/"
  fi
  if command -v push-guard >/dev/null 2>&1; then
    cmd="push-guard"
  else
    cmd="$DEST/bin/push-guard"
    path_note="
  Tip: add $(cygpath -w "$DEST/bin") to your PATH to run plain  push-guard  from PowerShell or Git Bash."
  fi
elif [ -d "$HOME/.local/bin" ]; then
  ln -sf "$DEST/push_guard.py" "$HOME/.local/bin/push-guard"
  cmd="push-guard"
else
  cmd="$DEST/push_guard.py"
fi

cat <<EOF

push-guard installed for:$( [ $# -eq 0 ] && echo " $scope" || echo "$scope" )

  Review a blocked push:   $cmd --review     (run it yourself, in a terminal)
  Audit a branch:          $cmd --scan origin/main..HEAD
  Optional name list:      add folders with your customer spreadsheets to
                           $DEST/term-sources.txt  (needs: pip install openpyxl)
  Uninstall:               $SRC/uninstall.sh
${path_note:-}
Note: repos that set their own core.hooksPath (e.g. husky) override push-guard.
EOF
